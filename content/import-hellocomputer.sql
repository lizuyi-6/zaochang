## 1. 一个真实问题

在键盘上敲下这样一行极简的 C 语言代码：

```c
int c = a + b;
```

经过编译器处理后，它变成了若干个保存在内存中的 32 位二进制数字（例如十六进制的 `0x012B1820`）。

此时，屏幕外的你按下了回车。几纳秒之后，变量 `c` 的内存单元中确实变成了 `a + b` 的计算结果。

在这个过程中，没有任何神秘的“意识”在理解代码，也没有任何软件在实时翻译。机箱内部只有一块通电的硅芯片（CPU）、几根平行的铜导线（总线）以及若干排列整齐的电容阵列（主存）。

一个核心问题自然浮现：

> **这串由高低电平构成的 01 代码，到底是如何在物理硬件中被一步步取出来、被硬件“看懂”、驱动算术电路完成求和，并最终精确写回到目标位置的？**

如果我们把 CPU 拆开，它内部的机械齿轮——程序计数器、寄存器、数据通路与控制信号，在每一个时钟节拍里究竟经历了什么？

