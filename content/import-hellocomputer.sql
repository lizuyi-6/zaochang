### 1. 时间局部性（Temporal Locality）
- **现象**：如果某个内存单元被访问，那么在不久的将来，它**极有可能被再次访问**。
- **软件根源**：循环结构中的计数变量、频繁调用的公共函数、累加器变量。
- **硬件对策**：将刚刚访问过的数据复制一份保存在最靠近 CPU 的极速 Cache 中，下次访问直接命中。

### 2. 空间局部性（Spatial Locality）
- **现象**：如果某个内存单元被访问，那么在不久的将来，**它物理相邻的内存单元极有可能被访问**。
- **软件根源**：顺序执行的代码指令流、一维数组的顺序遍历、连续存放的结构体成员。
- **硬件对策**：**每次访存不是只抓取单个字节，而是按“数据块（Cache Block / Line，如 64 字节）”成批打包调入高速缓存**。

