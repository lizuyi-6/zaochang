## 3. 核心概念深度剖析

### 1. 翻译（Translation）vs 解释（Interpretation）
- **翻译 (Compilation)**：将某一层的高级语言程序一次性完整转换成下一层的等价程序，然后再在低层机器上直接运行（如 C/C++ 经 `gcc` 编译为 ELF 目标二进制文件）。运行期**零翻译开销，执行速度最快**。
- **解释 (Interpretation)**：由低层机器上的一个解释器程序，逐句读取高级语言代码，边解释边执行，不生成独立的目标机器码文件（如 Python 虚拟机循环）。**灵活性高、跨平台好，但运行期开销大**。

### 2. 指令集架构（ISA - Instruction Set Architecture）的绝对核心地位
- **ISA 是软件与硬件之间的唯一物理分界线与法律契约**！
- **ISA 规定了什么**：
  1. 机器支持的所有操作码（加法、跳转、访存等）；
  2. 通用寄存器的数量、位宽与命名；
  3. 寻址方式（如何通过指令找到操作数的物理地址）；
  4. 内存编址方式（大端序/小端序、按字节编址）；
  5. 中断与异常的处理协议。
- **ISA 与微架构（Microarchitecture）的区别（408 核心重点）**：
  - **ISA 是“规范”**：告诉你这台机器能做什么；
  - **微架构是“实现”**：告诉你这台机器具体是怎么做的。
  - **例子**：Intel Core i9-14900K 和 AMD Ryzen 7 7800X3D 具有完全相同的 x86-64 ISA（同一段机器码两台电脑都能跑），但它们内部的流水线级数、Cache 大小、ALU 数量和分支预测算法完全不同！

