### 机制一：双符号位法（模 4 补码 / 变形补码）——大题最常考
- 在 ALU 内部，每个数分配 **2 个符号位**：`00` 表示正数，`11` 表示负数。
- **运算判定规则**：
  - `00`：结果为正，无溢出；
  - `11`：结果为负，无溢出；
  - **`01`**：最高符号位为 0（本应为正），第二符号位为 1（进位侵占）-> **正溢出（上溢）**；
  - **`10`**：最高符号位为 1（本应为负），第二符号位为 0（借位破坏）-> **负溢出（下溢）**；
  - **关键结论**：**最高符号位永远代表真实的理论符号！**

### 机制二：单符号位进位比较法
设 $C_s$ 为符号位产生的进位（向更高位的进位），$C_p$ 为最高数值位向符号位的进位：
$$\text{溢出标志 } OF = C_s \oplus C_p$$
- 若 $C_p=1, C_s=0$（数值位进位但符号位没进位）：$OF = 1 \oplus 0 = 1$（正溢出）；
- 若 $C_p=0, C_s=1$（数值位没进位但符号位进位）：$OF = 0 \oplus 1 = 1$（负溢出）；
- 硬件只需一个**异或门（XOR）**即可瞬间输出 $OF$ 信号。

### 机制三：$OF$ 标志与 $CF$ 标志的本质区别（408 必考死穴）

| 标志位名称 | 全称与功能 | 适用数据类型 | 判定规则 |
| :--- | :--- | :--- | :--- |
| **$OF$ 标志** | **Overflow Flag (溢出标志)** | **专门用于有符号数运算！** | $OF=1$ 表示有符号运算超出了有符号数范围，结果不可信。 |
| **$CF$ 标志** | **Carry Flag (进位/借位标志)** | **专门用于无符号数运算！** | 加法时 $CF=\text{最高位进位}$；减法时 $CF=\text{借位}$。$CF=1$ 表示无符号数产生进位或借位。 |

