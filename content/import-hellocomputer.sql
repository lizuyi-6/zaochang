## 2. 溢出（Overflow）的物理本质

在有限字长的计算机中，运算结果超出了该字长所能表示的最大范围，称为**溢出**。

以 8 位有符号数为例，表示范围是 $[-128, +127]$：
- $80 + 60 = 140 > 127$（**正溢出 / 上溢**）；
- $-80 + (-70) = -150 < -128$（**负溢出 / 下溢**）。

```text
    80 的补码:   0101 0000
+   60 的补码:   0011 1100
---------------------------
    运算结果:    1000 1100  (最高位符号位变成了 1，变成了 -116 的补码！)
```

由于最高数值位产生的进位直接“冲垮”了符号位，导致正数相加变成了负数。

