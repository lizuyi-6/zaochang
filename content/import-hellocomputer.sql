## 5. 新机制为什么必须出现？

为了在物理电路上稳定运行任何程序，冯·诺依曼架构确立了五个核心硬件部件：

```mermaid
flowchart TD
    subgraph Computer["冯·诺依曼计算机体系"]
        subgraph CPU["中央处理器 (CPU)"]
            CU["控制器 (Control Unit)<br/>按时钟节拍发号施令的状态机"]
            ALU["运算器 (ALU + 寄存器堆)<br/>执行算术逻辑操作的工厂"]
        end
        
        MEM["存储器 (Memory)<br/>统一保存指令与数据的仓库"]
        INPUT["输入设备 (Input)<br/>将外部信息转为电信号"]
        OUTPUT["输出设备 (Output)<br/>将处理结果呈现给外部"]
        
        INPUT --> MEM
        MEM --> OUTPUT
        MEM <==>|指令与数据流| CPU
        CU -.->|控制信号电平| ALU
        CU -.->|读写控制线| MEM
    end
```

在这套架构中，各部件的物理职责被严格界定：

1. **存储器（Memory）**：按地址编址的线性连续空间，指令（做什么）和数据（算什么）以平等的二进制形式混合存放在同一个物理存储体中。
2. **运算器（ALU + 寄存器堆）**：负责纯粹的代数与逻辑运算，内部包含高速寄存器来隔离外部总线延迟。
3. **控制器（CU）**：包含程序计数器（PC）和指令寄存器（IR），根据时钟脉冲，机械地进行“取指令 -> 译码分析 -> 生成控制电平”的循环。
4. **输入/输出设备（I/O）**：负责机器与外部世界的模数/数模转换。

