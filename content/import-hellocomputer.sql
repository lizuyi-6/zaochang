8 位二进制寄存器最多只能容纳 8 个比特，最高位产生的进位会物理溢出丢失。
这说明 8 位寄存器天然就是一个**模 $M = 2^8 = 256$ 的圆环系统**！

要计算 $A - B$，等价于计算：
$$A - B \equiv A + (256 - B) \pmod{256}$$
而 $(256 - B)$ 在二进制硬件里的极速生成方法，恰好就是——**“各位取反，末位加 1”**！

因为：
$$256 - B = (255 - B) + 1 = (11111111_2 - B) + 1$$
$11111111_2 - B$ 对应把 $B$ 的每一位 $0$ 变 $1$、$1$ 变 $0$（纯按位取反），最后加 $1$ 即可完成求补！

