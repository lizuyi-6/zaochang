## 4. 定点除法：加减交替法（不恢复余数法）

传统原码除法是“试商法”：若余数减去除数后为负，说明不够除，必须“恢复余数”（加上除数）。这种来回试探在硬件上极耗时间。

**加减交替法**利用数学变换消除了恢复余数的过程：
- 若当前余数 $R_i > 0$：商上 1，余数左移 1 位，下一轮减去除数（即 $2R_i - Y$）；
- 若当前余数 $R_i < 0$：商上 0，余数左移 1 位，下一轮**直接加上除数**（即 $2R_i + Y$）。

运算步数严格固定为 $n+1$ 步加减法，彻底消除了硬件时钟不确定性。

