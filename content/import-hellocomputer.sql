## 2. 我们最自然的第一反应

对于刚接触计算机底层的学习者，最直观的脑内模型通常是这样的：

> CPU 是一个聪明的大脑。内存里放着公式 `c = a + b`。CPU 伸出一只手去内存里把 `a` 和 `b` 抓过来，在脑子里的加法器算一下，再伸手把结果放回 `c` 的位置。

如果把这个直觉转换成硬件逻辑框图，很多人脑海中构想的“极简计算机”是这样的：

```mermaid
flowchart LR
    MEM["主存 (存放变量 a, b 和指令)"] <--> ALU["算术逻辑单元 (ALU 加法器)"]
    ALU --> CU["控制器 (大脑)"]
```

在这个朴素的直觉中：
1. 内存里的指令和数据是连在一起的，CPU 可以随时看懂；
2. 加法器（ALU）的两端直接连着内存里的变量 `a` 和 `b`；
3. 计算一旦发生，结果立刻通过导线流回内存的变量 `c`。

---

## 3. 如果真的这样实现，会发生什么？

现在，我们把这个直觉当作真实的硬件设计方案，尝试在物理电路上搭建它，看看会发生什么灾难性的物理冲突。

### 冲突一：导线延迟与输入震荡
ALU 是一个纯粹的组合逻辑门电路网络。门电路的输出取决于输入的电平。
内存（DRAM）距离 CPU 核心在物理上有数厘米的走线距离，电信号在印制电路板（PCB）上的传播需要时间（每纳秒约前进 15 厘米）。
如果将内存中的单元直接连接到 ALU 的输入引脚：
当操作数 `a` 的电平还在导线上颠簸传输、高低电平尚未稳定时，ALU 就会立刻根据半成品的残缺电平开始计算，输出端产生剧烈的高频振荡，产生不可预测的乱码输出。

### 冲突二：总线争用（一条路不能同时跑两辆车）
在物理实现上，连接 CPU 与内存的铜导线（数据总线）数量是有限的（例如 32 根线对应 32 位字长）。
一条指令要读取操作数 `a`，需要占用数据总线；读取操作数 `b`，也需要占用数据总线；把结果写回 `c`，还需要占用数据总线。
如果像直觉那样“同时抓取两个数并写回”，32 根铜线上会同时充斥着三个不同变量的电压，电平互相叠加彻底烧毁数据。

### 冲突三：没有记忆，状态瞬间丢失
组合逻辑电路是没有记忆能力的。
当加法器算出了 $a + b$ 的电压，如果这个电压要写回内存，就必须撤销原来输入端 `a` 和 `b` 的读取状态；
但输入状态一旦撤销，ALU 的输入立刻归零，ALU 的输出也瞬间归零，写回内存的数据就变成了 0！

**结论：硬件无法在一步之内完成“看指令、读两个数、计算、写回”。**

