$$T_2 = \frac{N \times \text{CPI}_2}{f_2} = \frac{10^8 \times 1.4}{2.5 \times 10^9} = \frac{1.4 \times 10^8}{2.5 \times 10^9} = 0.056 \text{ 秒 (56 ms)}$$

