## 5. 核心指标物理意义深度拆解

为了让这些符号在脑中具有实体感，我们逐一剖析它们的物理根基：

### 1. 指令数 $N$（Instruction Count）
- **定义**：一个程序在运行过程中**实际动态执行的机器指令总数**（不是静态编译出来的代码行数，循环体内的指令每跑一圈都会计入）。
- **决定因素**：算法复杂度（$O(n)$ vs $O(n^2)$）、编程语言效率、编译器优化等级（`-O0` vs `-O3`）以及指令集架构（ISA，RISC 与 CISC 所需指令条数不同）。

### 2. CPI（Cycles Per Instruction，每条指令平均周期数）
- **定义**：CPU 完成一条机器指令平均所花费的时钟节拍数。
- **决定因素**：微体系结构设计（单周期 CPU $\text{CPI}=1$；多周期非流水线 $\text{CPI}=4\sim 5$；超标量多发射 CPU $\text{CPI}<1$）。
- **综合 CPI 计算**：
  $$\text{综合 CPI} = \sum_{i=1}^{k} (\text{CPI}_i \times p_i)$$
  其中 $p_i$ 为程序中第 $i$ 类指令所占的比例，$\text{CPI}_i$ 为该类指令的平均周期数。

### 3. IPC（Instructions Per Cycle，每个时钟周期完成的指令数）
- **定义**：$\text{IPC} = \frac{1}{\text{CPI}}$。现代高性能处理器采用超标量架构，一个周期发射 4~8 条指令，IPC 通常大于 1。

### 4. MIPS（Million Instructions Per Second，每秒执行百万条指令数）
- **定义**：
  $$\text{MIPS} = \frac{N}{T \times 10^6} = \frac{f}{\text{CPI} \times 10^6}$$
- **局限性**：MIPS 不能跨指令集比较性能！因为 RISC 指令简单，完成同样任务可能需要 200 条指令（MIPS 虽高但指令多），而 CISC 只需要 50 条复杂指令，任务总用时反而更短。

### 5. MFLOPS / GFLOPS / TFLOPS（每秒执行百万/十亿/万亿次浮点运算）
- **定义**：
  $$\text{MFLOPS} = \frac{\text{程序中的浮点运算总次数}}{T \times 10^6}$$
- 用于客观衡量科学计算、深度学习及物理渲染的真实算力。

