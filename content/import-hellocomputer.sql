## 10. 性能模型与执行时间数学公式

执行一段程序所需的总 CPU 时间 $T_{\text{CPU}}$：

$$T_{\text{CPU}} = \text{程序包含的总指令数 } N \times \text{每条指令平均时钟周期数 CPI} \times \text{时钟周期 } T_{\text{clk}}$$

由于主频 $f = \frac{1}{T_{\text{clk}}}$，公式亦可精确表达为：

$$T_{\text{CPU}} = \frac{N \times \text{CPI}}{f}$$

