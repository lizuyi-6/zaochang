尾数右移丢弃的低位可能引起精度下降：
- **0 舍 1 入法**：移出的最高位如果是 1，在尾数末位加 1（类似四舍五入，可能再次引起右规）；
- **恒置 1 法**：只要移出位中含有 1，直接将尾数最低有效位置 1。

### 步骤五：溢出判定
- **上溢（Overflow）**：阶码经过调整后大于 254（$E > 254$），硬件触发浮点上溢异常；
- **下溢（Underflow）**：阶码经过调整后小于 0（$E < 0$），机器按 0.0 处理。

