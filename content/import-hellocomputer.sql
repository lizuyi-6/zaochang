## 4. 原来的模型在哪里撞墙？

上述物理冲突揭示了计算机设计中最根本的一对矛盾：

1. **组合逻辑的即时性**：加法器只要输入端电平稳定，纳秒级内就能输出结果，但它**不保存状态**。
2. **总线与外部存储的延迟性**：外部主存读取慢、总线带宽有限，**多个数据必须分时传输**。

要在慢速、分时复用的外部总线，与快速、无记忆的内部算术逻辑单元之间建立协调，必须在 CPU 内部引入两个关键机制：

- **暂存机制（寄存器）**：在 CPU 芯片内部制造若干个纳秒级响应的极速存储单元，先把操作数从内存接过来稳稳锁存住，给 ALU 提供持久稳定的电压输入。
- **节拍与状态机机制（控制器与时钟）**：将整个大任务粉碎为若干个不可再分的最小微操作，用时钟信号（Clock）严格规定：第 1 拍只取指令，第 2 拍只读操作数，第 3 拍只做加法，第 4 拍只写回结果。

这就是 1945 年冯·诺依曼（John von Neumann）与合作者确立的计算机体系结构的底层物理逻辑。

