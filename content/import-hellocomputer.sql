## 2. 五大步骤深度拆解与硬件法则

### 步骤一：对阶（小阶向大阶看齐）——408 大题第一步
- 计算阶差 $\Delta E = E_A - E_B$；
- **原则：小阶向大阶看齐**。将较小阶码的数其阶码增加到较大者的阶码，同时将其尾数**逻辑右移 $\Delta E$ 位**。
- **为什么不能“大阶向小阶看齐”？**
  如果大阶向小阶对齐，需要将大阶的尾数左移，这会导致最高位的有效数字被移出丢弃，造成无法挽回的巨大数值误差；而尾数右移只会丢失末尾的微小精度。

