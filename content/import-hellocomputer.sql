## 7. 跑一个完整案例

我们选择一个真实的执行场景，给所有部件填上具体数值，追踪一行加法代码的真实硬件执行：

### 初始状态与前置条件：
- 内存地址 `0x00401000` 处存放着编译好的机器指令：`ADD R3, R1, R2`（指令机器码为 `0x012B1820`）；
- 通用寄存器 `R1` 当前存有数值：`0x00000002`（十进制 2）；
- 通用寄存器 `R2` 当前存有数值：`0x00000003`（十进制 3）；
- 通用寄存器 `R3` 当前数值未知；
- 当前程序计数器 `PC = 0x00401000`；
- 主频为 1 GHz（每个时钟节拍 $T = 1.0 \text{ ns}$）。

现在，时钟发生器开始振荡，脉冲信号一次次推进：

### 阶段一：取指周期（Fetch Cycle）——把指令从内存搬到 CPU

1. **时钟节拍 $T_1$：建立访问地址**
   - 控制单元 CU 发出控制信号，使 PC 输出使能，MAR 写入使能。
   - 数据通路：$\text{PC} \to \text{MAR}$。
   - 物理状态：MAR 的 32 个触发器被置为 `0x00401000`，外部地址总线 AB 上的 32 根铜线呈现对应高低电平。

2. **时钟节拍 $T_2$：主存寻址与数据回传**
   - CU 向控制总线 CB 发出“读使能（Read Enable）”高电平。
   - 内存芯片内部的行/列译码器选中 `0x00401000` 对应的存储体。
   - 读出的 32 位电平流向数据总线 DB，送达 CPU 的 MDR 引脚。
   - 数据通路：$\text{Memory}[\text{MAR}] \to \text{DB} \to \text{MDR}$。
   - 物理状态：MDR 内部锁存器稳定保存 `0x012B1820`。

3. **时钟节拍 $T_3$：指令送入 IR，PC 自动加 4**
   - CU 发出信号，将 MDR 中的机器码复制到指令寄存器 IR。
   - 专用硬件加法线路将 PC 的值加 4（32 位指令占 4 个字节地址）。
   - 数据通路：$\text{MDR} \to \text{IR}$，同时 $\text{PC} + 4 \to \text{PC}$。
   - 物理状态：IR 保存 `0x012B1820`；$\text{PC}$ 变为 `0x00401004`，已经做好了下一条指令的准备。

### 阶段二：译码与读操作数周期（Decode & Operand Fetch）

1. **时钟节拍 $T_4$：译码与寄存器并行读取**
   - 指令寄存器 IR 的输出线直接连接到控制单元 CU 和寄存器堆的地址选择端。
   - CU 的组合逻辑译码器瞬间识别出 `0x012B1820` 是一条寄存器加法指令（ADD）。
   - 寄存器堆的读端口 A 选中 `R1`，输出引脚呈现电压 `0x00000002`；
   - 寄存器堆的读端口 B 选中 `R2`，输出引脚呈现电压 `0x00000003`；
   - 两个值通过专用数据内部总线，分别稳定呈现在 ALU 的左输入端 Input A 和右输入端 Input B。

### 阶段三：执行周期（Execute Cycle）

1. **时钟节拍 $T_5$：ALU 计算**
   - CU 向 ALU 的操作控制引脚输入加法功能码（如 `ALU_OP = 0010`）。
   - ALU 内部的 32 位超前进位加法器电路导通，电信号穿过逻辑门阵列：
     $$0\text{x}00000002 + 0\text{x}00000003 = 0\text{x}00000005$$
   - 标志寄存器 PSW 更新（$ZF=0, SF=0, OF=0, CF=0$）。
   - ALU 输出引脚稳定呈现电平 `0x00000005`。

### 阶段四：写回周期（Writeback Cycle）

1. **时钟节拍 $T_6$：写回寄存器堆**
   - CU 发出寄存器写使能信号（`RegWrite = 1`），目的寄存器地址端输入 `R3` 的编号。
   - 在时钟上升沿到来的瞬间，ALU 输出端的电平被锁存进 `R3` 触发器中。
   - 最终物理状态：`R3 = 0x00000005`。

