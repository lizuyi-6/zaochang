"""
Hello Computer · 实验 08: 多重中断处理与中断屏蔽字 (Interrupt Mask) 模拟
适用考点: 408 计组第十章·输入/输出系统 (中断响应优先级 vs 中断处理优先级、屏蔽字设置与中断嵌套轨迹)
"""
from typing import List, Dict

def simulate_nested_interrupts():
    """
    408 经典真题模型:
      设系统有 4 个中断源: 1, 2, 3, 4
      硬件响应优先级 (排队器固定): 1 > 2 > 3 > 4
      通过设置【中断屏蔽字 (Interrupt Mask)】调整后的处理优先级为: 2 > 4 > 1 > 3
      
      规则 (408 必背):
        - 屏蔽字中对应位为 1 表示屏蔽（禁止打断当前程序），为 0 表示开放中断。
        - 中断源自身的屏蔽位必须为 1 (不能自己打断自己)。
        - 优先级高于当前中断源的位置为 0，低于或等于的置为 1。
    """
    print(f"\n================ 多重中断屏蔽字与嵌套时序模拟 ================")
    print(f"中断源数量: 4 个 (1, 2, 3, 4)")
    print(f"硬件响应优先级: 1 > 2 > 3 > 4")
    print(f"目标处理优先级: 2 > 4 > 1 > 3 (通过屏蔽字动态修改)")
    
    # 构建屏蔽字表 (处理优先级 2 > 4 > 1 > 3)
    # 中断 2: 优先级最高，屏蔽所有 (1111)
    # 中断 4: 次高，仅被 2 打断 (1011)
    # 中断 1: 第三，可被 2, 4 打断 (1010)
    # 中断 3: 最低，可被 2, 4, 1 打断 (0010)
    masks = {
        1: "1 0 1 0",
        2: "1 1 1 1",
        3: "0 0 1 0",
        4: "1 0 1 1"
    }
    
    print("\n各中断源的中断服务程序入口设置的屏蔽字 (按 1, 2, 3, 4 位顺序):")
    for src in [1, 2, 3, 4]:
        print(f"  中断源 {src} 的屏蔽字: [{masks[src]}]")
        
    print("\n>>> 场景模拟:")
    print("  主程序运行中 -> 中断源 1 请求 -> CPU 响应 1，进入中断服务程序 1，加载屏蔽字 [1 0 1 0]")
    print("  -> 在 1 运行途中，中断源 3 与 2 同时请求：")
    print("     - 中断 3 对应屏蔽位为 1 (被屏蔽，挂起等待)")
    print("     - 中断 2 对应屏蔽位为 0 (允许打断！)")
    print("  -> CPU 暂停 1，嵌套进入中断服务程序 2，加载屏蔽字 [1 1 1 1]")
    print("  -> 2 执行完毕返回 1 继续执行 -> 1 执行完毕返回主程序 -> 响应之前挂起的中断 3")
    print("\n执行时序轨迹: 主程序 -> ISR(1)前半段 -> 【嵌套】ISR(2)全部 -> ISR(1)后半段 -> ISR(3)全部 -> 主程序")

if __name__ == "__main__":
    simulate_nested_interrupts()
