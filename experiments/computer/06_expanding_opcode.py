"""
Hello Computer · 实验 06: 扩展操作码 (Expanding Opcode) 编码与容量验证器
适用考点: 408 计组第六章·指令系统 (三地址、二地址、一地址、零地址指令操作码扩展原则与哈夫曼前缀编码)
"""

def verify_expanding_opcode():
    """
    408 经典真题场景:
      设指令字长 16 位，每个地址码占 4 位。
      设计一套包含:
        - K3 条三地址指令 (含 3 个地址码 A1, A2, A3, 剩余 4 位操作码)
        - K2 条二地址指令 (含 2 个地址码 A1, A2, 剩余 8 位操作码)
        - K1 条一地址指令 (含 1 个地址码 A1, 剩余 12 位操作码)
        - K0 条零地址指令 (无地址码, 剩余 16 位操作码)
    """
    print(f"\n================ 扩展操作码分配模拟 (16位指令字长, 4位地址码) ================")
    
    # 假设分配方案:
    # 4 位三地址操作码: 0000 ~ 1110 (共 15 条三地址指令), 留出 1111 作为二地址扩展标志
    k3 = 15
    unused_k3 = (1 << 4) - k3  # 1 个扩展前缀 (1111)
    
    # 8 位二地址操作码: 前缀 1111 + 后 4 位 (0000 ~ 1110, 共 15 条二地址指令), 留出 1111 1111 作为一地址扩展标志
    k2 = 15
    unused_k2 = unused_k3 * (1 << 4) - k2  # 1 个扩展前缀 (1111 1111)
    
    # 12 位一地址操作码: 前缀 1111 1111 + 后 4 位 (0000 ~ 1110, 共 15 条一地址指令), 留出 1111 1111 1111 作为零地址扩展标志
    k1 = 15
    unused_k1 = unused_k2 * (1 << 4) - k1
    
    # 16 位零地址指令: 最大可容纳条数
    max_k0 = unused_k1 * (1 << 4)
    
    print(f"分配方案参数:")
    print(f"  三地址指令数 K3 = {k3} 条 (占用 0000 ~ 1110, 剩余 {unused_k3} 个前缀 1111 用于扩展)")
    print(f"  二地址指令数 K2 = {k2} 条 (占用 1111 0000 ~ 1111 1110, 剩余 {unused_k2} 个前缀用于扩展)")
    print(f"  一地址指令数 K1 = {k1} 条 (占用 1111 1111 0000 ~ 1111 1111 1110, 剩余 {unused_k1} 个前缀用于扩展)")
    print(f"  => 此时最多还能容纳零地址指令数 K0 = {max_k0} 条！")
    
    print(f"\n408 核心不等式验证:")
    print(f"  公式: (2^4 - K3) * 2^4 * 2^4 * 2^4 - K2 * 2^4 * 2^4 - K1 * 2^4 = {max_k0}")
    print(f"  只要短操作码的前缀留出空位，就能向下按 2^n 倍数指数级扩展长操作码！")

if __name__ == "__main__":
    verify_expanding_opcode()
