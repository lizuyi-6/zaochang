- 什么是“状态”？为什么内存里的对象会丢失，而数据库里的表不会？
- 当两个用户在同一瞬间点击选课系统的最后一个名额时，到底是谁在决定谁能选上？是前端的代码、后端的代码，还是数据库的锁？

