/** Convert a Simplified string to Traditional (vocabulary first, then glyphs). */
export function toTW(s: string): string {
  let out = s;
  for (const [re, rep] of TW_PHRASES) out = out.replace(re, rep);
  return out.replace(/[\u4e00-\u9fff]/g, (ch) => TW_CHARS[ch] ?? ch);
}
